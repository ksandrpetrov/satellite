def _build_bot_welcome_html() -> str:
    tip = blockquote(
        "Добавь в название встречи 🍕 и слово «обед» — Чайка отметит её как обед в сводке."
    )
    head = replace_first_char_with_tg_emoji("🪶 Привет! Чайка на связи.\n\n", "🪶")
    return (
        f"{head}"
        "Выбери, что посмотреть:\n"
        "📅 <b>Сегодня</b> / ➡️ <b>Завтра</b> — план на день\n"
        "🗓 <b>Ближайшие</b> — события на неделю вперёд\n"
        "📨 <b>Приглашения</b> — встречи, которые ждут твоего ответа\n"
        "🛠 <b>Изменить статус</b> — изменить свой ответ на встречу\n"
        "👥 <b>Общие календари</b> — календари, к которым тебе открыли доступ\n"
        "➕ <b>Создать</b> — добавить встречу в свой календарь\n"
        "⚙️ <b>Настройки</b> — дайджест, аналитика, подключение\n\n"
        f"{tip}"
    )


def _build_bot_help_html() -> str:
    commands_block = expandable_blockquote(
        "/today, /tomorrow, /aftertomorrow — план дня\n"
        "/upcoming — ближайшие события\n"
        "/invitations — ответить на приглашения\n"
        "/manage — изменить статус встречи на неделе\n"
        "/foreign — общие календари\n"
        "/create — создать встречу\n"
        "/settings — настройки\n"
        "/digest, /stopdigest — включить или выключить дайджест на сегодня",
        threshold=2,
    )
    head = replace_first_char_with_tg_emoji("🪶 <b>Как пользоваться Чайкой</b>\n\n", "🪶")
    return (
        f"{head}"
        "Чайка собирает встречи из твоего календаря и приносит сводку дня.\n\n"
        "<b>Кнопки внизу:</b>\n"
        "📅 Сегодня, ➡️ Завтра — план на день\n"
        "🗓 Ближайшие — события на 7 дней\n"
        "📨 Приглашения — принять, отклонить или «может быть»\n"
        "🛠 Изменить статус — изменить свой ответ на встречу на ближайшей неделе\n"
        "👥 Общие календари — календари, к которым тебе открыли доступ\n"
        "➕ Создать событие — добавить встречу\n"
        "⚙️ Настройки — дайджест, аналитика, подключение\n\n"
        "<b>Команды:</b>\n"
        f"{commands_block}\n\n"
        "<i>Короткие команды: <code>td</code>, <code>tm</code>, <code>dat</code>.</i>"
    )


BOT_WELCOME_HTML = _build_bot_welcome_html()
BOT_HELP_HTML = _build_bot_help_html()

